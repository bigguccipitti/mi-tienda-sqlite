<h1 class="reveal">Return Policy</h1>

<article class="pagina-legal reveal">
    <p class="nota-practica">This is a student practice project — no real orders are fulfilled, so no real returns happen. This page is a template for learning purposes.</p>

    <h2>Return window</h2>
    <p>In a real store, this section would state how many days a customer has to request a return after delivery (commonly 14–30 days) and from what date that window starts counting.</p>

    <h2>Condition required for return</h2>
    <p>Since pieces here are pre-owned and sold in the condition described, a real policy would need to state clearly whether returns are accepted at all for pre-owned goods, and if so, what condition the item must be returned in.</p>

    <h2>Non-returnable items</h2>
    <p>Items marked final sale, or items where the condition disclosed at purchase matches the condition on return, would typically not be eligible.</p>

    <h2>How to request a return</h2>
    <p>A real policy would list a concrete way to start a return (an email address or a form), what information to include (order number, reason), and how long a response takes.</p>

    <h2>Refunds</h2>
    <p>This section would state how a refund is issued (original payment method), how long it takes to appear, and who pays for return shipping.</p>

    <h2>Authenticity disputes</h2>
    <p>If a buyer believes a piece doesn't match its description, a real policy would need a specific process for that — separate from a standard change-of-mind return.</p>
</article>

